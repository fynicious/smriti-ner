// Proxy-based helper languages that fall back to English for missing keys
function createFallbackTranslation(partial: Partial<TranslationStrings>): TranslationStrings {
  return new Proxy(partial as TranslationStrings, {
    get(target, prop: string) {
      return (target as unknown as Record<string, string>)[prop] ?? (fallback as unknown as Record<string, string>)[prop] ?? prop;
    },
  });
}

